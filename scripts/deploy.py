#!/usr/bin/env python3
"""
Deploy the four Intelligent Contracts to Studionet and record what was deployed.

    python scripts/deploy.py              # all four
    python scripts/deploy.py LEDGER_CONTRACT   # just one, by env var name

The deployer is the local "relayer" account in ~/.genlayer-arcade/accounts.json,
so the relayer that later submits on players' behalf is the owner of every
contract (BUILD_SPEC section 3). Its key is never written in this repository;
scripts/vercel_env.py pipes it into the Vercel project's env.

contracts/FROZEN.json records, per contract: the address, the deploy
transaction, the sha256 of the exact bytes sent, and when. lib/deployment.json
is written from it for the site, and scripts/deploy.md is regenerated.
"""

from __future__ import annotations

import datetime
import hashlib
import json
import sys

import chain as C

WEB_DEPLOYMENT = C.ROOT / "lib" / "deployment.json"
DEPLOY_MD = C.ROOT / "scripts" / "deploy.md"


def write_public(entry: dict) -> None:
    public = {
        "network": C.NETWORK,
        "chainId": C.CHAIN_ID,
        "rpc": C.RPC,
        "explorer": C.EXPLORER,
        "owner": entry.get("owner", ""),
        "contracts": {name: entry.get(name, {}).get("address", "") for name in C.CONTRACTS},
    }
    WEB_DEPLOYMENT.write_text(json.dumps(public, indent=2) + "\n", encoding="utf-8", newline="\n")
    rows = []
    for name, path in C.CONTRACTS.items():
        item = entry.get(name)
        if not item:
            continue
        rows.append(
            f"| `{name}` | `{path.relative_to(C.ROOT).as_posix()}` | [`{item['address']}`]({C.EXPLORER}/address/{item['address']}) "
            f"| [deploy tx]({C.EXPLORER}/tx/{item['tx']}) | `{item['sha256'][:16]}…` | {item['deployed_at']} |"
        )
    DEPLOY_MD.write_text(
        "# Deployments\n\n"
        "Generated by `python scripts/deploy.py` from `contracts/FROZEN.json`. Do not edit by hand.\n\n"
        f"Network: **Studionet** (chain {C.CHAIN_ID}, RPC {C.RPC}, runtime `{C.RUNTIME}`).\n\n"
        f"Owner (the relayer account): `{entry.get('owner', '')}`\n\n"
        "| Env var | Source | Address | Deploy | sha256 | Deployed (UTC) |\n|---|---|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n\n## Steps\n\n"
        "1. `python scripts/deploy.py` deploys all four from the relayer account and writes this file, "
        "`contracts/FROZEN.json` and `lib/deployment.json`.\n"
        "2. `python scripts/verify.py` reads each contract's code back from the chain and checks it against the sha256 here.\n"
        "3. `python scripts/vercel_env.py` sets `RELAYER_PRIVATE_KEY` and the four contract addresses in the Vercel project "
        "without printing the key.\n"
        "4. Open the first rounds from `/admin` (or `python scripts/rounds.py open-all`).\n",
        encoding="utf-8", newline="\n",
    )


def main() -> int:
    wanted = [a for a in sys.argv[1:] if a in C.CONTRACTS] or list(C.CONTRACTS)
    relayer = C.accounts("relayer")["relayer"]
    chain = C.Chain(relayer)
    print(f"network  {C.NETWORK} (chain {C.CHAIN_ID}) via {C.RPC}")
    print(f"deployer {relayer.address}")
    chain.ensure(relayer.address, minimum_gen=50)

    record = C.frozen()
    entry = record.setdefault("deployments", {}).setdefault(C.NETWORK, {})
    entry.update({"chain_id": C.CHAIN_ID, "rpc": C.RPC, "explorer": C.EXPLORER, "runtime": C.RUNTIME, "owner": relayer.address})
    for name in wanted:
        if entry.get(name):
            print(f"  {name} is frozen at {entry[name]['address']}; refusing to redeploy. Remove it from FROZEN.json by hand if you mean it.")
            continue
        path = C.CONTRACTS[name]
        # the hash of the exact bytes sent (chain.deploy reads the file as text, so LF)
        digest = hashlib.sha256(path.read_text(encoding="utf-8").encode("utf-8")).hexdigest()
        done = chain.deploy(path)
        entry[name] = {
            "address": done["address"],
            "tx": done["tx"],
            "sha256": digest,
            "file": path.relative_to(C.ROOT).as_posix(),
            "deployed_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        }
        C.save_frozen(record)
        print(f"  recorded {name}: {done['address']}  {C.EXPLORER}/tx/{done['tx']}")
    write_public(entry)
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
