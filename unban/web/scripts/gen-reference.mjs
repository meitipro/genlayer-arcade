#!/usr/bin/env node
/**
 * Generates the docs pages that must not drift from the code, then checks
 * every internal docs link. Runs before `next build`, so:
 *
 *   - a method cannot exist in contracts/unban.py and be missing from
 *     /docs/reference/contract, or the other way round;
 *   - the judge prompt on /docs/more/judge-prompt is the JUDGE constant, byte
 *     for byte;
 *   - /docs/reference/errors lists every refusal the contract can raise;
 *   - /docs/reference/addresses and /docs/more/evaluation come from
 *     deployed.json and eval/results.json, or say plainly that they do not
 *     exist yet;
 *   - a broken internal link fails the build.
 *
 * When the contract source is not reachable (a build from web/ alone), the
 * committed generated pages are kept as they are.
 */

import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = path.resolve(WEB, "..");
const DOCS = path.join(WEB, "content", "docs");
const CONTRACT = path.join(ROOT, "contracts", "unban.py");
const EXPLORER = "https://explorer-studio-dev.genlayer.com";

function write(rel, text) {
  const file = path.join(DOCS, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev !== text) fs.writeFileSync(file, text);
}

function frontmatter(title, description) {
  return `---\ntitle: ${title}\ndescription: ${description}\n---\n\n{/* Generated by web/scripts/gen-reference.mjs. Do not edit by hand. */}\n\n`;
}

const mdxEscape = (s) => s.replace(/[{}<>]/g, (c) => ({ "{": "&#123;", "}": "&#125;", "<": "&lt;", ">": "&gt;" })[c]);

function methods(src) {
  const out = [];
  const re = /@gl\.public\.(write\.payable|write|view)\n    def (\w+)\(\s*self(?:,\s*)?([\s\S]*?)\)\s*->\s*([^:]+):\n((?:        """[\s\S]*?"""\n)?)/g;
  let m;
  while ((m = re.exec(src))) {
    const kind = m[1] === "write.payable" ? "payable" : m[1];
    const params = m[3].split(",").map((p) => p.trim()).filter(Boolean);
    const doc = (m[5] || "").replace(/"""/g, "").replace(/\s+/g, " ").trim();
    out.push({ kind, name: m[2], params, returns: m[4].trim(), doc });
  }
  return out;
}

function refusals(src) {
  const set = new Set();
  const re = /E \+ "([^"]+)"/g;
  let m;
  while ((m = re.exec(src))) set.add(m[1]);
  const re2 = /E \+ ([a-z_]+) \+ " ([^"]+)"/g;
  while ((m = re2.exec(src))) set.add(`<field> ${m[2]}`);
  return [...set].sort();
}

function generate() {
  const src = fs.readFileSync(CONTRACT, "utf8");
  const ms = methods(src);
  if (ms.length !== 12) throw new Error(`expected 12 public methods in contracts/unban.py, found ${ms.length}`);

  const header = src.split("\n").slice(0, 2).join("\n");
  let ref = frontmatter("Contract", "Every public method of contracts/unban.py, generated from the source at build time.");
  ref += `The contract is one file, [\`contracts/unban.py\`](https://github.com/meitipro/genlayer-unban/blob/main/contracts/unban.py), on the runtime Studio Next loads:\n\n\`\`\`python\n${header}\n\`\`\`\n\n`;
  ref += `| Method | Kind | Parameters | Returns |\n|---|---|---|---|\n`;
  for (const m of ms) ref += `| \`${m.name}\` | ${m.kind} | ${m.params.map((p) => `\`${p}\``).join(", ") || "none"} | \`${m.returns}\` |\n`;
  ref += `\nPayable methods take GEN with the call (\`value\`). Views need no wallet. Amounts are wei as integers (1 GEN = 10^18).\n\n`;
  for (const m of ms) {
    ref += `## ${m.name}\n\n\`\`\`python\n${m.name}(${m.params.join(", ")}) -> ${m.returns}\n\`\`\`\n\n`;
    if (m.doc) ref += `${mdxEscape(m.doc)}\n\n`;
    ref += `Kind: **${m.kind}**.\n\n`;
  }
  write("reference/contract.mdx", ref);

  let errors = frontmatter("Errors", "Every refusal the contract can raise, generated from the source.");
  errors += "A refusal is still an ACCEPTED transaction: validators agree the call should fail. The site reads the leader's execution result and shows the sentence below without its `[EXPECTED]` prefix. `<field>` stands for the name of the text that was empty or too long (name, case, statement, evidence, reply, rule text, ladder label).\n\n| Refusal |\n|---|\n";
  for (const r of refusals(src)) errors += `| ${mdxEscape(r)} |\n`;
  errors += "\nModel failures carry `[LLM_ERROR]` (empty, bad json, bad verdict, reduced level is not on the ladder, reduced level is not lighter). They never agree across validators, so the round retries with a different committee rather than storing a ruling.\n";
  write("reference/errors.mdx", errors);

  const judge = src.match(/JUDGE = """([\s\S]*?)"""/)[1];
  let jp = frontmatter("The judge prompt", "The rubric validators run, word for word, as it sits in the contract.");
  jp += "This is the `JUDGE` constant in `contracts/unban.py`, copied at build time. A test (`test_rubric_is_section_3_word_for_word`) holds it to the build spec.\n\n";
  jp += "```text\n" + judge + "\n```\n\n";
  jp += "## What fills each slot\n\n| Slot | Filled with |\n|---|---|\n";
  jp += "| `{rules}` | Every rule as `Rule n: text First offence Pa, repeat Pb.`, then the ladder lightest first, from the rule set in force on the ban date |\n";
  jp += "| `{rule}` | The number the moderator cited and its text |\n";
  jp += "| `{level}` | The level applied and its label, then how many earlier upheld or reduced rulings the member has in this court, which is what tells a first offence from a repeat |\n";
  jp += "| `{evidence}` | The moderator's quoted messages |\n| `{statement}` | `Case: …, banned YYYY-MM-DD` and the member's statement |\n| `{reply}` | The member's reply, or `(none)` |\n\n";
  jp += "Every value passes through `_fence()`, which replaces `<` and `>` with `(` and `)`, so no party can close its `<<<…>>>` block and open a forged one.\n\n";
  jp += "## How validators agree\n\nThe leader's answer is normalised: the verdict must be one of the three, and a REDUCED level must be on the ladder and lighter than the level applied, or it is rejected as a model failure. Each validator runs the prompt itself and agrees only when `(verdict, level)` matches. The reason sentence is stored from the leader and never compared.\n";
  write("more/judge-prompt.mdx", jp);
}

function addresses() {
  const file = path.join(ROOT, "deployed.json");
  let page = frontmatter("Addresses and network", "Where Unban lives, and the network it runs on.");
  page += "| Network | Value |\n|---|---|\n| Name | GenLayer Studio Next |\n| Chain id | 61997 (0xF22D) |\n| RPC | `https://studio-next.genlayer.com/api` |\n| Explorer | [explorer-studio-dev.genlayer.com](https://explorer-studio-dev.genlayer.com) |\n| Faucet | Studio's `sim_fundAccount`, behind **Get test GEN** in the site header |\n\n";
  if (fs.existsSync(file)) {
    const d = JSON.parse(fs.readFileSync(file, "utf8"));
    page += `## The contract\n\n| | |\n|---|---|\n| Address | [\`${d.contract}\`](${EXPLORER}/address/${d.contract}) |\n| Deploy transaction | [\`${d.deploy_tx.slice(0, 18)}…\`](${EXPLORER}/tx/${d.deploy_tx}) |\n| Deployer | [\`${d.deployer}\`](${EXPLORER}/address/${d.deployer}) |\n| Source sha256 | \`${d.sha256}\` |\n`;
  } else {
    page += "## The contract\n\n<Callout type=\"warn\">No deployment is recorded in this repository yet (`deployed.json` is absent). `python scripts/deploy.py` deploys `contracts/unban.py` and writes it; this page is regenerated from that file at the next build. The site reads the address from `NEXT_PUBLIC_UNBAN_CONTRACT`.</Callout>\n";
  }
  write("reference/addresses.mdx", page);
}

function evaluation() {
  const file = path.join(ROOT, "eval", "results.md");
  const e2e = path.join(ROOT, "eval", "e2e.md");
  let page = frontmatter("Evaluation results", "The golden cases, run through real consensus, with every transaction.");
  page += "The golden set is `eval/golden.json`: nine cases with an expected ruling and three held-out cases (H1 to H3) with none, all written before the first run. `python eval/run_golden.py` runs each one through appeal, respond, reply and judge on Studio Next and writes `eval/results.md` exactly as the chain answered. Nothing is tuned against the held-out cases.\n\n";
  if (fs.existsSync(file)) {
    page += mdxEscape(fs.readFileSync(file, "utf8").replace(/^# .*\n/, "")).replace(/&lt;(\/?)(a|b)&gt;/g, "") + "\n";
  } else {
    page += "<Callout type=\"warn\">No run is recorded in this repository yet (`eval/results.md` is absent), so no ruling is shown here. This page is regenerated from that file at the next build.</Callout>\n\n";
  }
  page += "## End-to-end path\n\n";
  page += fs.existsSync(e2e)
    ? mdxEscape(fs.readFileSync(e2e, "utf8").replace(/^# /, "### ")) + "\n"
    : "`python scripts/e2e.py` walks the reviewer's path (open a court, appeal, a refused stranger, the moderator's answer, the reply, judge, read back, withdraw) and records each transaction to `eval/e2e.md`. No run is recorded yet.\n";
  write("more/evaluation.mdx", page);
}

function lastUpdated() {
  const out = {};
  const walk = (dir) => {
    for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, f.name);
      if (f.isDirectory()) walk(p);
      else if (f.name.endsWith(".mdx")) {
        const rel = path.relative(DOCS, p).split(path.sep).join("/");
        try {
          const iso = execSync(`git log -1 --format=%cI -- "${p}"`, { cwd: WEB, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
          if (iso) out[rel] = iso;
        } catch {
          /* no git in this build: no date shown */
        }
      }
    }
  };
  walk(DOCS);
  const target = path.join(WEB, "content", "last-updated.json");
  if (Object.keys(out).length || !fs.existsSync(target)) fs.writeFileSync(target, JSON.stringify(out, null, 2) + "\n");
}

function checkLinks() {
  const pages = new Set(["/docs"]);
  const files = [];
  const walk = (dir) => {
    for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, f.name);
      if (f.isDirectory()) walk(p);
      else if (f.name.endsWith(".mdx")) {
        files.push(p);
        const rel = path.relative(DOCS, p).split(path.sep).join("/").replace(/\.mdx$/, "").replace(/(^|\/)index$/, "");
        pages.add(rel ? `/docs/${rel}` : "/docs");
      }
    }
  };
  walk(DOCS);
  const site = new Set(["/", "/courts", "/rulings", "/new", "/mod", "/llms.txt", "/llms-full.txt"]);
  const broken = [];
  for (const f of files) {
    const text = fs.readFileSync(f, "utf8");
    for (const m of text.matchAll(/\]\((\/[^)\s#]*)(#[^)\s]*)?\)|href="(\/[^"#]*)/g)) {
      const target = (m[1] ?? m[3]).replace(/\/$/, "") || "/";
      if (target.startsWith("/docs") ? !pages.has(target) : !site.has(target) && !/^\/(c|a)\/\d+/.test(target)) {
        broken.push(`${path.relative(WEB, f)} -> ${target}`);
      }
    }
  }
  if (broken.length) {
    console.error("Broken internal docs links:\n  " + broken.join("\n  "));
    process.exit(1);
  }
  console.log(`docs: ${pages.size} pages, internal links ok`);
}

if (fs.existsSync(CONTRACT)) {
  generate();
  addresses();
  evaluation();
  console.log("docs: generated contract reference, errors, judge prompt, addresses, evaluation");
} else {
  console.log("docs: contracts/unban.py not reachable from this build; keeping the committed generated pages");
}
lastUpdated();
checkLinks();
