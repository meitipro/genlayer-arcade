/**
 * Runs before every dev and build. Everything here is generated from a file
 * that runs or a record the chain produced, so the docs cannot drift from the
 * contract:
 *
 *   generated/unban.py          the contract, byte for byte, for /deploy
 *   generated/deployment.json   ../deployment.json (written by scripts/deploy.py), or {}
 *   generated/results.json      ../eval/results.json, or no cases
 *   content/docs/reference/contract.mdx   every public method, from the source
 *   content/docs/reference/errors.mdx     every refusal sentence, from the source
 *   content/docs/reference/addresses.mdx  the deployment record
 *   content/docs/more/judge-prompt.mdx    the JUDGE constant, word for word
 *   content/docs/more/evaluation.mdx      eval/results.json as a table with transactions
 *   public/llms.txt, public/llms-full.txt  the docs, for agents
 *
 * Then it fails the build on any internal docs link that points nowhere.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WEB = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = path.join(WEB, "..");
const DOCS = path.join(WEB, "content", "docs");
const GEN_DIR = path.join(WEB, "generated");
const EXPLORER = "https://explorer-studio-dev.genlayer.com";
const REPO_BLOB = "https://github.com/meitipro/genlayer-arcade/blob/claude/inspiring-dijkstra-6cskv8/unban";

fs.mkdirSync(GEN_DIR, { recursive: true });

const readJson = (file, fallback) => {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    return fallback;
  }
};
const write = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) fs.writeFileSync(file, text);
};

// ---- the contract and the records -------------------------------------------
const source = fs.readFileSync(path.join(ROOT, "contracts", "unban.py"), "utf8");
write(path.join(GEN_DIR, "unban.py"), source);
const deployment = readJson(path.join(ROOT, "deployment.json"), {});
write(path.join(GEN_DIR, "deployment.json"), JSON.stringify(deployment, null, 2) + "\n");
const results = readJson(path.join(ROOT, "eval", "results.json"), { cases: [] });
write(path.join(GEN_DIR, "results.json"), JSON.stringify(results, null, 2) + "\n");
const walk = readJson(path.join(ROOT, "evidence", "walk.json"), null);

// ---- contract reference, parsed from the source ---------------------------------
const lines = source.split("\n");
const methods = [];
for (let i = 0; i < lines.length; i++) {
  const deco = /^\s+@gl\.public\.(write\.payable|write|view)\s*$/.exec(lines[i]);
  if (!deco) continue;
  let sig = "";
  let j = i + 1;
  while (j < lines.length && !sig.includes(":\n")) {
    sig += lines[j].trim() + " ";
    if (/\)\s*(->\s*[^:]+)?:\s*$/.test(lines[j])) break;
    j++;
  }
  const m = /def (\w+)\(self,?\s*(.*?)\)\s*(?:->\s*([^:]+))?:/.exec(sig);
  if (!m) continue;
  // The method's own explanation: its docstring, or the comments at the top of its body.
  const notes = [];
  let k = j + 1;
  if (/^\s+"""/.test(lines[k] ?? "")) {
    let doc = lines[k].trim().replace(/^"""/, "");
    if (doc.endsWith('"""')) notes.push(doc.replace(/"""$/, ""));
    else {
      if (doc) notes.push(doc);
      k++;
      while (k < lines.length && !lines[k].includes('"""')) notes.push(lines[k].trim()), k++;
      const last = lines[k].trim().replace(/"""$/, "");
      if (last) notes.push(last);
    }
  } else {
    while (/^\s+#/.test(lines[k] ?? "")) notes.push(lines[k].trim().replace(/^#\s?/, "")), k++;
  }
  // The refusals this method can raise directly.
  const body = [];
  for (let b = j + 1; b < lines.length && !/^\s{4}(@|def |# --)/.test(lines[b]); b++) body.push(lines[b]);
  const refusals = [...body.join("\n").matchAll(/UserError\(E \+ "([^"]+)"\)/g)].map((x) => x[1]);
  methods.push({ kind: deco[1], name: m[1], params: m[2].trim(), returns: (m[3] || "None").trim(), notes: notes.join(" ").replace(/\s+/g, " ").trim(), refusals, line: i + 1 });
}
if (methods.length !== 12) throw new Error(`expected 12 public methods in contracts/unban.py, found ${methods.length}`);

const KIND = { "write.payable": "write, payable", write: "write", view: "view" };
const esc = (t) => t.replace(/[{}<>]/g, (c) => ({ "{": "&#123;", "}": "&#125;", "<": "&lt;", ">": "&gt;" })[c]);
let ref = `---
title: Contract reference
description: Every public method of contracts/unban.py, generated from the source at build time.
---

{/* Generated by web/scripts/prepare-data.mjs from contracts/unban.py. Do not edit by hand. */}

One contract, twelve public methods. Runtime header \`py-genlayer:5jycge4q\` (Studio Next, SDK v0.3). Amounts are in wei
(1 GEN = 10^18). Views return JSON text; parse it.

| Method | Kind | Returns |
| --- | --- | --- |
${methods.map((m) => `| [\`${m.name}\`](#${m.name.replace(/_/g, "-")}) | ${KIND[m.kind]} | \`${m.returns}\` |`).join("\n")}

`;
for (const m of methods) {
  ref += `## ${m.name.replace(/_/g, "\\_")}\n\n\`\`\`python\n${m.name}(${m.params}) -> ${m.returns}\n\`\`\`\n\n`;
  ref += `**${KIND[m.kind]}** · [source line ${m.line}](${REPO_BLOB}/contracts/unban.py#L${m.line})\n\n`;
  if (m.notes) ref += `${esc(m.notes)}\n\n`;
  if (m.refusals.length) ref += `Refuses with: ${m.refusals.map((r) => `\`${r}\``).join(", ")}.\n\n`;
}
write(path.join(DOCS, "reference", "contract.mdx"), ref);

// ---- errors -------------------------------------------------------------------------
const all = [...new Set([...source.matchAll(/UserError\((E|L) \+ "([^"]+)"\)/g)].map((x) => `${x[1]}|${x[2]}`))];
const expected = all.filter((x) => x.startsWith("E|")).map((x) => x.slice(2));
const model = all.filter((x) => x.startsWith("L|")).map((x) => x.slice(2));
write(path.join(DOCS, "reference", "errors.mdx"), `---
title: Errors
description: Every refusal the contract can raise, generated from the source.
---

{/* Generated by web/scripts/prepare-data.mjs from contracts/unban.py. */}

A refused write is still a decided transaction: validators agree that the refusal is the right result. The site and the
scripts treat a write as successful only when the outcome is accepted **and** the execution finished with a return; anything
else shows the sentence below.

## Refusals (\`[EXPECTED]\`)

Deterministic, so the leader and every validator must produce the same sentence.

${expected.map((e) => `- \`${e}\``).join("\n")}

## Model failures (\`[LLM_ERROR]\`)

Raised inside \`judge\` when the model's answer does not parse into the closed set. One retry happens inside the same block; if
the second answer fails too, validators disagree by design, so the round rotates rather than storing a guess.

${model.map((e) => `- \`${e}\``).join("\n")}

## Reads

A view that raises comes back from Studio as a bare "execution failed", without the sentence. The site reads that as "not
found".
`);

// ---- addresses -------------------------------------------------------------------------
const deployedLine = deployment.address
  ? `| Unban contract | [\`${deployment.address}\`](${EXPLORER}/address/${deployment.address}) |
| Deploy transaction | [\`${deployment.deploy_tx}\`](${EXPLORER}/tx/${deployment.deploy_tx}) |
| Source sha256 | \`${deployment.source_sha256}\` |
| Deployed from commit | \`${deployment.deployed_from_commit || "not recorded"}\` |
| Deployed at | ${deployment.deployed_at || "not recorded"} |`
  : `| Unban contract | Not deployed from this repository yet: \`deployment.json\` is absent. Run \`python scripts/deploy.py\`, or deploy from [/deploy](/deploy). |`;
write(path.join(DOCS, "reference", "addresses.mdx"), `---
title: Addresses and network
description: The network Unban runs on and the deployment this site reads, generated from deployment.json.
---

{/* Generated by web/scripts/prepare-data.mjs from deployment.json. */}

| | |
| --- | --- |
| Network | GenLayer Studio Next |
| Chain id | 61997 (0xF22D) |
| RPC | \`https://studio-next.genlayer.com/api\` |
| Explorer | [explorer-studio-dev.genlayer.com](${EXPLORER}) |
| Runtime | \`py-genlayer:5jycge4q8k23462jtb0b9fyey1s9qz928sz2nbrd9mg4sxqg2qng\` |
| Currency | GEN, 18 decimals, test only |
${deployedLine}

\`scripts/verify_source.py\` reads the contract back from the chain and compares it with \`contracts/unban.py\`.
`);

// ---- the judge prompt -----------------------------------------------------------------------
const judge = /JUDGE = """([\s\S]*?)"""/.exec(source)[1].replace(/\{\{/g, "{").replace(/\}\}/g, "}");
write(path.join(DOCS, "more", "judge-prompt.mdx"), `---
title: The judge prompt, word for word
description: The JUDGE constant in contracts/unban.py, extracted at build time.
---

{/* Generated by web/scripts/prepare-data.mjs from the JUDGE constant. */}

This is the whole question validators ask. \`{rules}\` is built by the contract from the stored rules and ladder (each rule with
its first-offence and repeat level, then the ladder, then how many earlier upheld or reduced rulings the member has in this
court). Every caller text passes through \`_fence\`, which turns \`<\` and \`>\` into \`(\` and \`)\` so nobody can close a \`<<< >>>\`
block from inside it.

\`\`\`text
${judge}
\`\`\`

## How validators agree

The leader parses the answer into \`{verdict, level, reason}\`. Each validator runs the same prompt itself and agrees only when
its verdict **and** its level are identical to the leader's. The reason sentence is the leader's, stored for the appeal page,
and never compared.

The normaliser refuses a REDUCED level that is not on the ladder or is not lighter than the level applied, so the bot only
ever receives a real penalty.
`);

// ---- evaluation ------------------------------------------------------------------------------
const cases = results.cases ?? [];
const scored = cases.filter((c) => c.pass === true || c.pass === false);
const held = cases.filter((c) => c.pass === null && c.verdict);
const seal = fs.existsSync(path.join(ROOT, "eval", "golden.sha256")) ? fs.readFileSync(path.join(ROOT, "eval", "golden.sha256"), "utf8").trim() : "";
const row = (c) => {
  const last = c.judge_attempts?.[c.judge_attempts.length - 1]?.hash ?? "";
  const tx = last ? `[${last.slice(0, 10)}…](${EXPLORER}/tx/${last})` : "";
  const mark = c.pass === null ? "–" : c.pass ? "yes" : "**no**";
  return `| ${c.id} | ${`${c.expected} ${c.expected_level ?? ""}`.trim()} | ${`${c.verdict ?? ""} ${c.level ?? ""}`.trim()} | ${mark} | ${esc(c.reason ?? "")} | ${tx} |`;
};
const walkBlock = walk
  ? `## The reviewer's path, walked from fresh accounts

Run by \`scripts/walk.py\` on contract \`${walk.contract}\`. Every step is a transaction:

| Step | Result | Transaction |
| --- | --- | --- |
${walk.steps.map((s) => `| ${s.step} | ${s.ok ? "accepted" : `refused: ${esc(String(s.refusal).replace(/^\[[A-Z_]+\]\s*/, ""))}`} | [${s.hash.slice(0, 10)}…](${s.explorer}) |`).join("\n")}
`
  : `## The reviewer's path

\`scripts/walk.py\` has not been run against a deployment from this repository yet, so there is nothing to show here.`;
write(path.join(DOCS, "more", "evaluation.mdx"), `---
title: Evaluation results with transactions
description: The golden cases and the held-out cases, through real consensus on Studio Next, exactly as they came out.
---

{/* Generated by web/scripts/prepare-data.mjs from eval/results.json and evidence/walk.json. */}

The golden set in \`eval/golden.json\` was sealed before the first run: \`${seal || "golden.sha256 missing"}\`.
\`eval/run_golden.py\` refuses to run if the file no longer matches, so the prompt was never tuned against it. Held-out cases H1 to
H3 have no expected answer and are published as they came out.

${cases.length
  ? `Scored: **${scored.filter((c) => c.pass).length} of ${scored.length}**.

| Case | Expected | Ruling | Pass | Reason | Judge tx |
| --- | --- | --- | --- | --- | --- |
${[...scored, ...held].map(row).join("\n")}`
  : "No golden run has been recorded for this deployment yet: `eval/results.json` is absent. Nothing is shown rather than a guess."}

${walkBlock}
`);

// ---- llms.txt ---------------------------------------------------------------------------------
const pages = [];
const walkDir = (dir) => {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walkDir(full);
    else if (name.endsWith(".mdx")) pages.push(full);
  }
};
walkDir(DOCS);
const slugOf = (file) => {
  const rel = path.relative(DOCS, file).replace(/\\/g, "/").replace(/\.mdx$/, "");
  return "/docs" + (rel === "index" ? "" : "/" + rel.replace(/\/index$/, ""));
};
const parsed = pages.map((file) => {
  const text = fs.readFileSync(file, "utf8");
  const fm = /^---\n([\s\S]*?)\n---\n?/.exec(text);
  const title = /title:\s*(.*)/.exec(fm?.[1] ?? "")?.[1]?.trim() ?? slugOf(file);
  const description = /description:\s*(.*)/.exec(fm?.[1] ?? "")?.[1]?.trim() ?? "";
  const body = text.slice(fm ? fm[0].length : 0).replace(/\{\/\*[\s\S]*?\*\/\}\n*/g, "").trim();
  return { file, slug: slugOf(file), title, description, body };
});
const site = (process.env.NEXT_PUBLIC_SITE_URL || "").replace(/\/$/, "");
write(path.join(WEB, "public", "llms.txt"), `# Unban

> Ban appeals for online communities, decided on GenLayer by the community's own written rules.

${parsed.map((p) => `- [${p.title}](${site}${p.slug}): ${p.description}`).join("\n")}
`);
write(path.join(WEB, "public", "llms-full.txt"), parsed.map((p) => `# ${p.title}\n\nURL: ${site}${p.slug}\n\n${p.body}\n`).join("\n---\n\n"));

// ---- broken internal links fail the build --------------------------------------------------------
const slugs = new Set(parsed.map((p) => p.slug));
const SITE_ROUTES = ["/", "/courts", "/rulings", "/new", "/mod", "/deploy"];
const broken = [];
for (const p of parsed) {
  for (const m of p.body.matchAll(/\]\((\/[^)#\s]*)(#[^)]*)?\)|href="(\/[^"#]*)/g)) {
    const target = (m[1] ?? m[3]).replace(/\/$/, "") || "/";
    if (target.startsWith("/docs") ? !slugs.has(target) : !SITE_ROUTES.includes(target) && !/^\/(c|a)\/\d+/.test(target)) {
      broken.push(`${path.relative(WEB, p.file)} -> ${target}`);
    }
  }
}
if (broken.length) {
  console.error("Broken internal links:\n  " + broken.join("\n  "));
  process.exit(1);
}
console.log(`prepare-data: ${methods.length} methods, ${expected.length + model.length} errors, ${parsed.length} docs pages, ${cases.length} eval cases, contract ${deployment.address || "not deployed"}`);
